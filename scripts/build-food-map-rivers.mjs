/**
 * 一次性数据管道：从 OSM 水系数据生成 hk-rivers.ts。
 * 河流不属于 natural=coastline，需要独立水层，否则渲染成陆地。
 *
 * 数据获取：
 *   curl -X POST https://overpass-api.de/api/interpreter --data 'data=[out:json];(
 *     way["waterway"~"river|riverbank|drain|canal|stream"](22.24,114.05,22.56,114.18);
 *     way["waterway"~"river|riverbank|drain|canal|stream"](22.24,114.18,22.56,114.30);
 *     relation["waterway"~"river|riverbank"](22.24,114.05,22.56,114.30););out geom;'
 *
 * 用法：node scripts/build-food-map-rivers.mjs <water.json> <out.ts>
 * 只取 waterway=river 的线要素与全部 river relation（河面），
 * 排除 stream/drain 山坑引水道（避免满图细小蓝线）。
 */
import { readFileSync, writeFileSync } from "node:fs";

import { assembleRings } from "./lib/osm-rings.mjs";

const [inputPath, outputPath] = process.argv.slice(2);
if (!inputPath || !outputPath) {
  console.error("usage: node scripts/build-food-map-rivers.mjs <in.json> <out.ts>");
  process.exit(1);
}

const LNG0 = 114.05;
const LAT_TOP = 22.62;
const K = 1991;
const COS = Math.cos((22.4 * Math.PI) / 180);
const project = ([lng, lat]) => [
  Math.round((lng - LNG0) * COS * K * 10) / 10,
  Math.round((LAT_TOP - lat) * K * 10) / 10,
];

const data = JSON.parse(readFileSync(inputPath, "utf8"));
const ways = data.elements.filter((e) => e.type === "way");
const relations = data.elements.filter((e) => e.type === "relation");

function coordsToPath(coords, close) {
  const pts = [];
  for (const coord of coords) {
    const p = project(coord);
    const last = pts[pts.length - 1];
    if (last && Math.hypot(p[0] - last[0], p[1] - last[1]) < 2) continue;
    pts.push(p);
  }
  if (pts.length < 2) return "";
  return "M" + pts.map((p) => `${p[0]} ${p[1]}`).join("L") + (close ? "Z" : "");
}

const areaPaths = [];
for (const relation of relations) {
  const outers = assembleRings(
    relation.members.filter(
      (m) => m.type === "way" && (m.role === "outer" || m.role === ""),
    ),
  );
  const inners = assembleRings(
    relation.members.filter((m) => m.type === "way" && m.role === "inner"),
  );
  for (const ring of [...outers, ...inners]) {
    const path = coordsToPath(ring, true);
    if (path) areaPaths.push(path);
  }
}
// waterway=riverbank 的 way 本身就是面
for (const way of ways) {
  if (way.tags?.waterway !== "riverbank") continue;
  const path = coordsToPath(
    way.geometry.map((g) => [g.lon, g.lat]),
    true,
  );
  if (path) areaPaths.push(path);
}

const linePaths = [];
let shenzhenRiverExcluded = 0;
for (const way of ways) {
  if (way.tags?.waterway !== "river") continue;
  // 深圳河为界河，已由虚线边界表达，不再画水系蓝（用户决定）
  const name = [
    way.tags?.name,
    way.tags?.["name:zh"],
    way.tags?.["name:zh-Hant"],
    way.tags?.["name:en"],
  ]
    .filter(Boolean)
    .join(" ");
  if (/深圳河|Sham Chun|Shenzhen River/i.test(name)) {
    shenzhenRiverExcluded += 1;
    continue;
  }
  const path = coordsToPath(
    way.geometry.map((g) => [g.lon, g.lat]),
    false,
  );
  if (path) linePaths.push(path);
}
if (shenzhenRiverExcluded === 0) {
  console.warn(
    "warning: no Shenzhen River way matched the exclusion patterns — naming may have changed upstream",
  );
}

const ts = `/**
 * GENERATED by scripts/build-food-map-rivers.mjs — 请勿手改。
 * 来源：OpenStreetMap waterway=river/riverbank（© OpenStreetMap contributors, ODbL）。
 * 海由画布底色承担；本文件是内陆河流层（渲染为与海同色）。
 */
export const HK_RIVER_AREA_PATHS: readonly string[] = ${JSON.stringify(areaPaths, null, 2)};

export const HK_RIVER_LINE_PATHS: readonly string[] = ${JSON.stringify(linePaths, null, 2)};
`;
writeFileSync(outputPath, ts);
console.log(
  `wrote ${outputPath}: ${areaPaths.length} area paths, ${linePaths.length} line paths, ${ts.length} bytes`,
);
